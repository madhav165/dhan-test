create or replace view nse500_extended as
select distinct on (symbol)
    symbol,
    company_name,
    industry,
    series,
    isin,
    coalesce(
        (select last_synced from nifty500_constituents c where c.symbol = s.symbol limit 1),
        snapshot_date::timestamptz
    ) as last_synced
from (
    select symbol, company_name, industry, series, isin, snapshot_date
    from nifty500_snapshots
    union all
    select symbol, company_name, industry, series, isin, last_synced::date
    from nifty500_constituents
) s
order by symbol, snapshot_date desc;
